// Helper: Normalize stop/landmark names for fuzzy matching
export function normalizeStopName(name = "") {
  let s = String(name).trim().toLowerCase();
  s = s.replace(/chaupar/g, "chopad");
  s = s.replace(/choupad/g, "chopad");
  s = s.replace(/fort/g, "");
  s = s.replace(/palace/g, "");
  s = s.replace(/temple/g, "");
  s = s.replace(/bazaar/g, "");
  s = s.replace(/bazar/g, "");
  s = s.replace(/\s+/g, "");
  return s;
}

// Calculate standard JCTSL ticket fare by distance or stop count
export function calculateBusFare(stopsCount, isAC = false) {
  const estDist = stopsCount * 1.4;
  if (isAC) {
    if (estDist <= 2) return 10;
    if (estDist <= 5) return 15;
    if (estDist <= 10) return 25;
    if (estDist <= 15) return 35;
    if (estDist <= 20) return 40;
    return 50;
  } else {
    if (estDist <= 2) return 5;
    if (estDist <= 5) return 10;
    if (estDist <= 10) return 15;
    if (estDist <= 15) return 20;
    if (estDist <= 20) return 25;
    if (estDist <= 30) return 30;
    if (estDist <= 40) return 35;
    return 40;
  }
}

// Advanced Multi-Hop Routing Engine (Up to 3 Transfers / 4 Buses)
export function findMultiHopBusRoute(sourceInput, destInput) {
  const srcStopNorm = normalizeStopName(landmarkToBusStop[sourceInput.toLowerCase()] || sourceInput);
  const dstStopNorm = normalizeStopName(landmarkToBusStop[destInput.toLowerCase()] || destInput);

  if (srcStopNorm === dstStopNorm) return null;

  const matchStop = (stops, targetNorm) => {
    return stops.findIndex(s => {
      const sn = normalizeStopName(s);
      return sn === targetNorm || sn.includes(targetNorm) || targetNorm.includes(sn);
    });
  };

  // 1. Direct Route Check (0 Transfers)
  for (const route of busRoutes) {
    const sIdx = matchStop(route.stops, srcStopNorm);
    const dIdx = matchStop(route.stops, dstStopNorm);

    if (sIdx !== -1 && dIdx !== -1 && sIdx !== dIdx) {
      const stopsPassed = route.stops.slice(Math.min(sIdx, dIdx), Math.max(sIdx, dIdx) + 1);
      const isReverse = sIdx > dIdx;
      const count = Math.abs(dIdx - sIdx);

      return {
        type: 'direct',
        transfers: 0,
        busNumber: route.routeNo,
        routeName: route.name,
        sourceStop: route.stops[sIdx],
        destStop: route.stops[dIdx],
        fare: calculateBusFare(count, route.service.includes("AC")),
        time: count * 3 + 6,
        waitingTimeMinutes: Math.round(route.frequencyMins / 2),
        route: {
          routeNumber: route.routeNo,
          routeName: route.name,
          stopsCount: count,
          stopsPassed: isReverse ? stopsPassed.reverse() : stopsPassed
        }
      };
    }
  }

  // 2. 1-Transfer Check (2 Buses)
  let bestOneTransfer = null;
  for (const r1 of busRoutes) {
    const sIdx = matchStop(r1.stops, srcStopNorm);
    if (sIdx === -1) continue;

    for (let tIdx = 0; tIdx < r1.stops.length; tIdx++) {
      if (tIdx === sIdx) continue;
      const transferStop = r1.stops[tIdx];
      const tNorm = normalizeStopName(transferStop);

      for (const r2 of busRoutes) {
        if (r2.routeNo === r1.routeNo) continue;
        const r2TIdx = matchStop(r2.stops, tNorm);
        const r2DIdx = matchStop(r2.stops, dstStopNorm);

        if (r2TIdx !== -1 && r2DIdx !== -1 && r2TIdx !== r2DIdx) {
          const c1 = Math.abs(tIdx - sIdx);
          const c2 = Math.abs(r2DIdx - r2TIdx);
          const fare = calculateBusFare(c1, r1.service.includes("AC")) + calculateBusFare(c2, r2.service.includes("AC"));
          const time = (c1 + c2) * 3 + 18;

          const candidate = {
            type: 'transfer_1',
            transfers: 1,
            sourceStop: r1.stops[sIdx],
            transferStop,
            destStop: r2.stops[r2DIdx],
            fare,
            time,
            waitingTimeMinutes: 10,
            route1: {
              routeNumber: r1.routeNo,
              routeName: r1.name,
              boardStop: r1.stops[sIdx],
              alightStop: transferStop,
              stopsCount: c1
            },
            route2: {
              routeNumber: r2.routeNo,
              routeName: r2.name,
              boardStop: transferStop,
              alightStop: r2.stops[r2DIdx],
              stopsCount: c2
            }
          };

          if (!bestOneTransfer || candidate.time < bestOneTransfer.time) {
            bestOneTransfer = candidate;
          }
        }
      }
    }
  }

  if (bestOneTransfer) return bestOneTransfer;

  // 3. 2-Transfer Check (3 Buses)
  let bestTwoTransfers = null;
  for (const r1 of busRoutes) {
    const sIdx = matchStop(r1.stops, srcStopNorm);
    if (sIdx === -1) continue;

    for (let t1Idx = 0; t1Idx < r1.stops.length; t1Idx++) {
      if (t1Idx === sIdx) continue;
      const t1Stop = r1.stops[t1Idx];
      const t1Norm = normalizeStopName(t1Stop);

      for (const r2 of busRoutes) {
        if (r2.routeNo === r1.routeNo) continue;
        const r2T1Idx = matchStop(r2.stops, t1Norm);
        if (r2T1Idx === -1) continue;

        for (let t2Idx = 0; t2Idx < r2.stops.length; t2Idx++) {
          if (t2Idx === r2T1Idx) continue;
          const t2Stop = r2.stops[t2Idx];
          const t2Norm = normalizeStopName(t2Stop);

          for (const r3 of busRoutes) {
            if (r3.routeNo === r2.routeNo || r3.routeNo === r1.routeNo) continue;
            const r3T2Idx = matchStop(r3.stops, t2Norm);
            const r3DIdx = matchStop(r3.stops, dstStopNorm);

            if (r3T2Idx !== -1 && r3DIdx !== -1 && r3T2Idx !== r3DIdx) {
              const c1 = Math.abs(t1Idx - sIdx);
              const c2 = Math.abs(t2Idx - r2T1Idx);
              const c3 = Math.abs(r3DIdx - r3T2Idx);

              const fare = calculateBusFare(c1) + calculateBusFare(c2) + calculateBusFare(c3);
              const time = (c1 + c2 + c3) * 3 + 28;

              const candidate = {
                type: 'transfer_2',
                transfers: 2,
                sourceStop: r1.stops[sIdx],
                transferStop1: t1Stop,
                transferStop2: t2Stop,
                destStop: r3.stops[r3DIdx],
                fare,
                time,
                waitingTimeMinutes: 15,
                route1: { routeNumber: r1.routeNo, routeName: r1.name, boardStop: r1.stops[sIdx], alightStop: t1Stop, stopsCount: c1 },
                route2: { routeNumber: r2.routeNo, routeName: r2.name, boardStop: t1Stop, alightStop: t2Stop, stopsCount: c2 },
                route3: { routeNumber: r3.routeNo, routeName: r3.name, boardStop: t2Stop, alightStop: r3.stops[r3DIdx], stopsCount: c3 }
              };

              if (!bestTwoTransfers || candidate.time < bestTwoTransfers.time) {
                bestTwoTransfers = candidate;
              }
            }
          }
        }
      }
    }
  }

  if (bestTwoTransfers) return bestTwoTransfers;

  // Fallback direct mock if search points are out of scope
  return {
    type: 'direct',
    transfers: 0,
    busNumber: "AC 1",
    routeName: "Sanganer To Kukas",
    sourceStop: sourceInput,
    destStop: destInput,
    fare: 20,
    time: 25,
    waitingTimeMinutes: 8,
    route: {
      routeNumber: "AC 1",
      routeName: "Sanganer To Kukas",
      stopsCount: 6,
      stopsPassed: [sourceInput, "Badi Chopad", "Ramgarh Mode", "Jal Mahal", destInput]
    }
  };
}

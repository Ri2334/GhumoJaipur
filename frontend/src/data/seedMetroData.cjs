const parsedPayload = [];

METRO_LINES_SPEC.forEach(lineSpec => {
  const lineCode = lineSpec.line_color.substring(0, 1).toUpperCase();
  lineSpec.stations.forEach((st, idx) => {
    const isInter = st.interchange.length > 0;
    const stnId = `STN-${lineCode}-${(idx + 1).toString().padStart(2, '0')}`;
    
    parsedPayload.push({
      station_id: stnId,
      station_name: st.name,
      line_color: lineSpec.line_color,
      line_number: lineSpec.line_number,
      is_interchange: isInter,
      interchange_lines: isInter ? st.interchange : [lineSpec.line_color],
      sequence_index: idx + 1,
      terminal_mappings: {
        start: lineSpec.start,
        end: lineSpec.end
      }
    });
  });
});

